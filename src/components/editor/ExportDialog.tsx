export function ExportDialog({ open, onOpenChange }: ExportDialogProps) {
  const { tokens, themeName } = useThemeStore();
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState("css");

  const outputs: Record<string, string> = {
    css: generateCssVars(tokens),
    w3c: generateW3CTokens(tokens, themeName),
    tailwind: generateTailwindConfig(tokens),
  };

  const handleCopy = async () => {
    await navigator.clipboard.writeText(outputs[activeTab]);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-2xl">
        <DialogHeader>
          <DialogTitle>Export Theme</DialogTitle>
          <DialogDescription>
            Copy the generated code for your chosen format.
          </DialogDescription>
        </DialogHeader>

        <Tabs value={activeTab} onValueChange={setActiveTab}>
          <div className="flex items-center justify-between">
            <TabsList>
              <TabsTrigger value="css">CSS Variables</TabsTrigger>
              <TabsTrigger value="w3c">W3C Tokens</TabsTrigger>
              <TabsTrigger value="tailwind">Tailwind Config</TabsTrigger>
            </TabsList>
            <Button size="sm" variant="outline" onClick={handleCopy}>
              {copied ? (
                <><Check className="h-3.5 w-3.5 mr-1.5" /> Copied</>
              ) : (
                <><Copy className="h-3.5 w-3.5 mr-1.5" /> Copy</>
              )}
            </Button>
          </div>

          {(["css", "w3c", "tailwind"] as const).map((tab) => (
            <TabsContent key={tab} value={tab}>
              <pre className="max-h-96 overflow-auto rounded-[var(--radius)] bg-[var(--muted)] p-4 text-xs font-mono text-[var(--foreground)] whitespace-pre leading-relaxed">
                {outputs[tab]}
              </pre>
            </TabsContent>
          ))}
        </Tabs>
      </DialogContent>
    </Dialog>
  );
}
