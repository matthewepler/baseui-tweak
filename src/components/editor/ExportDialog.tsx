"use client";

import React, { useState } from "react";
import { useThemeStore } from "@/store/themeStore";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { Check, Copy } from "lucide-react";
import { semanticTokensToCssVars } from "@/lib/token-utils";

interface ExportDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

function generateCssVars(tokens: ReturnType<typeof useThemeStore.getState>["tokens"]): string {
  const lightVars: Record<string, string> = {
    ...tokens.light,
    "--radius": tokens.borderRadius,
    "--font-sans": tokens.fontFamily.sans,
    "--font-serif": tokens.fontFamily.serif,
    "--font-mono": tokens.fontFamily.mono,
  };

  const lightSection = semanticTokensToCssVars(lightVars, ":root");
  const darkSection = semanticTokensToCssVars(tokens.dark as unknown as Record<string, string>, ".dark");

  return `/* Generated by BaseUI Tweak — W3C Design Tokens */\n\n${lightSection}\n\n${darkSection}`;
}

function generateW3CTokens(
  tokens: ReturnType<typeof useThemeStore.getState>["tokens"],
  themeName: string
): string {
  const tree: Record<string, unknown> = {
    $schema: "https://tr.designtokens.org/format/",
    $description: `${themeName} theme tokens`,
    color: {
      $description: "Semantic color tokens",
      light: {} as Record<string, unknown>,
      dark: {} as Record<string, unknown>,
    },
    borderRadius: {
      base: {
        $type: "dimension",
        $value: tokens.borderRadius,
        $description: "Default border radius",
      },
    },
    typography: {
      fontFamily: {
        sans: { $type: "fontFamily", $value: tokens.fontFamily.sans },
        serif: { $type: "fontFamily", $value: tokens.fontFamily.serif },
        mono: { $type: "fontFamily", $value: tokens.fontFamily.mono },
      },
    },
  };

  for (const [key, value] of Object.entries(tokens.light)) {
    (tree.color as Record<string, unknown>).light = {
      ...((tree.color as Record<string, unknown>).light as Record<string, unknown>),
      [key]: { $type: "color", $value: value },
    };
  }
  for (const [key, value] of Object.entries(tokens.dark)) {
    (tree.color as Record<string, unknown>).dark = {
      ...((tree.color as Record<string, unknown>).dark as Record<string, unknown>),
      [key]: { $type: "color", $value: value },
    };
  }

  return JSON.stringify(tree, null, 2);
}

